/**
 * @fileoverview Script to build configs and the rule index for `eslint-markdown`.
 * Usage: `node path/to/build-config.js`
 */

// --------------------------------------------------------------------------------
// Import
// --------------------------------------------------------------------------------

import { readdirSync, writeFileSync } from 'node:fs';
import { createJiti } from 'jiti';
import prettier from 'prettier';

// --------------------------------------------------------------------------------
// Helper
// --------------------------------------------------------------------------------

/**
 * @param {'all' | 'base' | 'recommended' | 'stylistic'} configName
 * @param {Record<string, string>} rules
 */
async function generateConfig(configName, rules) {
  const url = new URL(
    `../packages/eslint-markdown/src/configs/${configName}.ts`,
    import.meta.url,
  );
  const prettierConfig = await prettier.resolveConfig(url);
  const code = `
/**
 * @fileoverview \`${configName}\` configuration.
 * WARNING: This file is autogenerated using the \`scripts/build-config.js\`
 */

// --------------------------------------------------------------------------------
// Import
// --------------------------------------------------------------------------------

import markdown from '@eslint/markdown';
import type { ESLint, Linter } from 'eslint';

// --------------------------------------------------------------------------------
// Export
// --------------------------------------------------------------------------------

export default function ${configName}(plugin: ESLint.Plugin) {
  return {
    name: 'md/${configName}',
    files: ['**/*.md'],
    plugins: {
      markdown,
      get md() {
        return plugin;
      }
    },
    languageOptions: {
      frontmatter: 'yaml',
    },
    language: 'markdown/gfm',
    ${configName === 'base' ? '' : `rules: ${JSON.stringify(rules)},`}
  } as const satisfies Linter.Config;
}
`.trimStart();

  writeFileSync(
    url,
    await prettier.format(code, { filepath: url.pathname, ...prettierConfig }),
  );
}

/** @param {string[]} ruleNames */
async function generateRuleIndex(ruleNames) {
  const url = new URL('../packages/eslint-markdown/src/rules/index.ts', import.meta.url);
  const prettierConfig = await prettier.resolveConfig(url);
  const rules = ruleNames.map(name => ({
    name,
    identifier: name.replace(/-[a-z]/gu, match => match[1].toUpperCase()),
  }));
  const code = `
/**
 * @fileoverview Rule index.
 * WARNING: This file is autogenerated using the \`scripts/build-config.js\`
 */

/* eslint sort-imports: 'error', sort-keys: 'error' */

${rules.map(({ name, identifier }) => `import ${identifier} from './${name}.js';`).join('\n')}

export default {
${rules.map(({ name, identifier }) => `'${name}': ${identifier},`).join('\n')}
};
`.trimStart();

  writeFileSync(
    url,
    await prettier.format(code, { filepath: url.pathname, ...prettierConfig }),
  );
}

// --------------------------------------------------------------------------------
// Script
// --------------------------------------------------------------------------------

const jiti = createJiti(import.meta.url);

const ruleNames = readdirSync(
  new URL('../packages/eslint-markdown/src/rules/', import.meta.url),
)
  .filter(name => !name.endsWith('.test.ts') && name !== 'index.ts')
  .map(name => name.slice(0, -3))
  .sort();

const rules = await Promise.all(
  ruleNames.map(async ruleName => {
    const rule =
      /** @type {{ meta: { docs: { recommended?: boolean, stylistic?: boolean } } }} */ (
        await jiti.import(`../packages/eslint-markdown/src/rules/${ruleName}.ts`, {
          default: true,
        })
      );
    return { ruleName, rule };
  }),
);

/** @type {Record<string, string>} */
const allRules = {};
/** @type {Record<string, string>} */
const baseRules = {};
/** @type {Record<string, string>} */
const recommendedRules = {};
/** @type {Record<string, string>} */
const stylisticRules = {};

for (const { ruleName, rule } of rules) {
  allRules[`md/${ruleName}`] = 'error';

  if (rule.meta.docs.recommended === true) {
    recommendedRules[`md/${ruleName}`] = 'error';
  }

  if (rule.meta.docs.stylistic === true) {
    stylisticRules[`md/${ruleName}`] = 'error';
  }
}

await Promise.all([
  generateConfig('all', allRules),
  generateConfig('base', baseRules),
  generateConfig('recommended', recommendedRules),
  generateConfig('stylistic', stylisticRules),
  generateRuleIndex(ruleNames),
]);
